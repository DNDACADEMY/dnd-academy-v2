"""Compare dnd.ac's published home with the repository and emit an idempotent CMS seed."""

import argparse
from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps/web/src"
SOURCE = "https://dnd.ac/"
STATS = {
    "누적 지원자 수": "cumulativeApplicants",
    "총 참가자 수": "totalParticipants",
    "총 프로젝트 수": "totalProjects",
}


class SponsorParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.link = None
        self.sponsors = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "a":
            self.link = attrs.get("href")
        if tag == "img" and attrs.get("src", "").startswith("/assets/logos/sponsors/"):
            self.sponsors.append({
                "name": attrs["alt"], "url": None if self.link == "#" else self.link,
                "logoPath": attrs["src"], "visible": True,
            })

    def handle_endtag(self, tag):
        if tag == "a":
            self.link = None


def collect(html):
    flight = "".join(
        json.loads(chunk)[1]
        for chunk in re.findall(r"self\.__next_f\.push\((\[1,.*?\])\)</script>", html)
    )
    faq_match = re.search(r'"faqItems":', flight)
    if not faq_match:
        raise ValueError("Could not locate publicly rendered FAQ answers")
    faqs, _ = json.JSONDecoder().raw_decode(flight[faq_match.end():])
    if not faqs or any(not row.get("question") or not row.get("answer") for row in faqs):
        raise ValueError("FAQ contains an empty question or answer")
    if len(set(row["question"] for row in faqs)) != len(faqs):
        raise ValueError("FAQ contains duplicate questions")

    counts = {key: int(re.search(r'"count":(\d+),"title":"' + label + '"', flight)[1])
              for label, key in STATS.items()}
    dropouts = re.search(r'"count":(\d+),"title":"(\d+)기 이탈자"', flight)
    counts.update(dropouts=int(dropouts[1]), dropoutCohort=int(dropouts[2]), asOf=None)
    local_counts = json.loads((WEB / "lib/assets/data/total_count_status.json").read_text())
    if any(counts[key] != value for key, value in local_counts.items()):
        raise ValueError("Public counters differ from the repository source")

    parser = SponsorParser()
    parser.feed(html)
    source = (WEB / "components/organisms/SponsorSection/index.tsx").read_text()
    local = [
        (name, None if url == "#" else url, f"/assets/logos/sponsors/{file}")
        for name, url, file in re.findall(r"{ sponsor: '([^']+)', url: '([^']+)', image: '([^']+)' }", source)
    ]
    if local != [(row["name"], row["url"], row["logoPath"]) for row in parser.sponsors] or not local:
        raise ValueError("Public sponsor links or logos differ from the repository source")
    sponsor_copy = re.search(r'<strong>DND</strong>[^<]*<strong>서비스유지</strong>([^<]+)', html)
    sponsor_contact = re.search(r'href="([^"]+)"[^>]*><span>후원 문의하기', html)
    if not sponsor_copy or not sponsor_contact:
        raise ValueError("Could not locate sponsor copy or link")
    subtitle = "DND는 서비스유지" + unescape(sponsor_copy[1]).strip()
    sponsor_info = {"description": subtitle, "contactUrl": unescape(sponsor_contact[1])}

    public_projects = list(dict.fromkeys(map(int, re.findall(r'"href":"/projects/(\d+)"', flight))))
    projects = json.loads((WEB / "lib/assets/data/projects.json").read_text())
    expected = [row["id"] for row in sorted(projects, key=lambda row: -int(row["flag"].rstrip("기") or 0))
                if row.get("thumbnail")][:20]
    if public_projects != expected:
        raise ValueError(f"Public slider differs from the repository source: {public_projects} vs {expected}")

    return {
        "stats": counts, "sponsorInfo": sponsor_info, "automaticProjects": True,
        "faqs": [{**row, "visible": True} for row in faqs],
        "sponsors": parser.sponsors, "projectIds": public_projects,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--html", type=Path, help="Use a previously captured public home response")
    parser.add_argument("--sql", action="store_true", help="Emit SQL instead of a dry-run summary")
    args = parser.parse_args()
    html = args.html.read_text() if args.html else urlopen(SOURCE, timeout=20).read().decode()
    payload = collect(html)
    if args.sql:
        data = json.dumps(payload, ensure_ascii=False, indent=2)
        if "$home_source$" in data:
            raise ValueError("Unexpected SQL delimiter in public data")
        print("-- Generated by scripts/import-home-cms.py from the public dnd.ac home.")
        print(f"select public.seed_home_cms($home_source$\n{data}\n$home_source$::jsonb);")
    else:
        json.dump({"source": SOURCE, "faqs": len(payload["faqs"]), "sponsors": len(payload["sponsors"]),
                   "sliderProjects": len(payload["projectIds"]), "stats": payload["stats"]},
                  sys.stdout, ensure_ascii=False, indent=2)
        print()


if __name__ == "__main__":
    main()
