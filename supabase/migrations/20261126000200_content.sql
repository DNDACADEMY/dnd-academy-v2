create type public.content_kind as enum ('project', 'organizer', 'review');
create type public.revision_state as enum ('draft', 'published', 'archived');

create table public.media_assets (
  id uuid primary key default gen_random_uuid(),
  bucket text not null check (bucket in ('cms-drafts', 'cms-public')),
  object_key text not null,
  mime text not null check (mime in ('image/webp', 'application/pdf')),
  bytes bigint not null check (bytes between 1 and 209715200),
  sha256 text not null check (sha256 ~ '^[a-f0-9]{64}$'),
  ready boolean not null default true,
  unique (bucket, object_key)
);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('cms-drafts','cms-drafts',false,209715200,array['image/webp','application/pdf']),
  ('cms-public','cms-public',true,209715200,array['image/webp','application/pdf']);

create table public.cms_uploads (
  object_key uuid primary key default gen_random_uuid(),
  actor uuid not null references auth.users,
  mime text not null check (mime in ('image/webp', 'application/pdf')),
  bytes bigint not null check (bytes between 1 and 209715200),
  created_at timestamptz not null default now()
);

create table public.skills (
  id bigint generated always as identity primary key,
  label text not null unique
);

create table public.projects (id integer generated by default as identity primary key check (id >= 0));
create table public.organizers (id integer generated by default as identity primary key check (id >= 0));
create table public.reviews (id integer generated by default as identity primary key check (id >= 0));

create table public.project_revisions (
  id bigint generated always as identity primary key,
  parent_id integer not null references public.projects,
  version integer not null check (version > 0),
  edit_number integer not null default 1 check (edit_number > 0),
  editor uuid references auth.users on delete set null,
  state public.revision_state not null,
  name text not null,
  title text not null,
  description text not null,
  cohort_id bigint not null references public.cohorts,
  thumbnail_id uuid references public.media_assets,
  pdf_id uuid references public.media_assets,
  legacy_thumbnail text,
  legacy_pdf text,
  unique (parent_id, version)
);

create table public.organizer_revisions (
  id bigint generated always as identity primary key,
  parent_id integer not null references public.organizers,
  version integer not null check (version > 0),
  edit_number integer not null default 1 check (edit_number > 0),
  editor uuid references auth.users on delete set null,
  state public.revision_state not null,
  name text not null,
  author text not null,
  position text not null check (position in ('개발','디자인','마케팅','운영','마스코트')),
  introduction text not null,
  mbti text not null,
  emoji text,
  is_archived boolean not null,
  thumbnail_id uuid references public.media_assets,
  legacy_thumbnail text,
  unique (parent_id, version)
);

create table public.review_revisions (
  id bigint generated always as identity primary key,
  parent_id integer not null references public.reviews,
  version integer not null check (version > 0),
  edit_number integer not null default 1 check (edit_number > 0),
  editor uuid references auth.users on delete set null,
  state public.revision_state not null,
  name text not null,
  position text not null,
  body text not null,
  cohort_id bigint references public.cohorts,
  project_id integer references public.projects,
  original_project_name text not null default '',
  unique (parent_id, version)
);

create index projects_published_cohort on public.project_revisions (cohort_id) where state = 'published';
create index reviews_published_project on public.review_revisions (project_id) where state = 'published';

create table public.project_revision_images (
  revision_id bigint references public.project_revisions on delete cascade,
  ordinal integer check (ordinal >= 0),
  media_id uuid references public.media_assets,
  legacy_url text,
  check (media_id is not null or legacy_url is not null),
  primary key (revision_id, ordinal)
);

create table public.organizer_revision_details (
  revision_id bigint references public.organizer_revisions on delete cascade,
  kind text check (kind in ('now','previous','role','recommendation','interests','share')),
  ordinal integer check (ordinal >= 0),
  body text not null,
  primary key (revision_id, kind, ordinal)
);

do $$
declare kind text;
begin
  foreach kind in array array['project','organizer','review'] loop
    execute format('create unique index %I on public.%I (parent_id,state) where state in (''draft'',''published'')',
      kind || '_active_revision', kind || '_revisions');
    execute format('create table public.%I (
      revision_id bigint references public.%I on delete cascade,
      ordinal integer check (ordinal >= 0),
      kind text not null,
      url text not null,
      primary key (revision_id,ordinal))', kind || '_revision_links', kind || '_revisions');
    if kind <> 'review' then
      execute format('create table public.%I (
        revision_id bigint references public.%I on delete cascade,
        skill_id bigint references public.skills,
        ordinal integer not null check (ordinal >= 0),
        primary key (revision_id,skill_id),
        unique (revision_id,ordinal))', kind || '_revision_skills', kind || '_revisions');
    end if;
  end loop;
end $$;

-- The returned JSON is a transport projection from relational rows.
create function public.content_data(kind public.content_kind, revision bigint) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  result jsonb;
  links jsonb;
  skill_list jsonb;
begin
  execute format('select coalesce(jsonb_agg(jsonb_build_object(''kind'',kind,''url'',url) order by ordinal),''[]'')
    from public.%I where revision_id = $1', kind || '_revision_links') into links using revision;
  if kind <> 'review' then
    execute format('select coalesce(jsonb_agg(s.label order by x.ordinal),''[]'') from public.%I x
      join public.skills s on s.id = x.skill_id where x.revision_id = $1', kind || '_revision_skills')
    into skill_list using revision;
  end if;

  case kind
    when 'project' then
      select jsonb_build_object('id', p.parent_id, 'editNumber', p.edit_number, 'revisionId', p.id,
        'name', p.name, 'title', p.title, 'description', p.description, 'cohort', c.ordinal,
        'thumbnailId', p.thumbnail_id, 'pdfId', p.pdf_id, 'legacyThumbnail', p.legacy_thumbnail, 'legacyPdf', p.legacy_pdf,
        'images', coalesce((select jsonb_agg(jsonb_build_object('mediaId',media_id,'legacyUrl',legacy_url) order by ordinal)
          from public.project_revision_images where revision_id = p.id), '[]'), 'skills', skill_list)
      into result from public.project_revisions p join public.cohorts c on c.id = p.cohort_id where p.id = revision;
    when 'organizer' then
      select jsonb_build_object('id', o.parent_id, 'editNumber', o.edit_number, 'revisionId', o.id,
        'name', o.name, 'author', o.author, 'position', o.position, 'description', o.introduction, 'mbti', o.mbti,
        'emoji', o.emoji, 'isArchived', o.is_archived, 'thumbnailId', o.thumbnail_id, 'legacyThumbnail', o.legacy_thumbnail,
        'details', coalesce((select jsonb_agg(jsonb_build_object('kind',d.kind,'body',d.body) order by d.kind,d.ordinal)
          from public.organizer_revision_details d where d.revision_id = o.id), '[]'), 'skills', skill_list)
      into result from public.organizer_revisions o where o.id = revision;
    when 'review' then
      select jsonb_build_object('id', r.parent_id, 'editNumber', r.edit_number, 'revisionId', r.id,
        'name', r.name, 'position', r.position, 'description', r.body, 'cohort', c.ordinal,
        'projectId', r.project_id, 'originalProjectName', r.original_project_name)
      into result from public.review_revisions r left join public.cohorts c on c.id = r.cohort_id where r.id = revision;
  end case;
  return result || jsonb_build_object('links', links);
end $$;

create function public.published_content(kind public.content_kind, selected_id integer default null) returns setof jsonb
language plpgsql stable set search_path = '' as $$
begin
  return query execute format('select public.content_data($1,id) from public.%I
    where state = ''published'' and ($2 is null or parent_id = $2) order by parent_id', kind || '_revisions')
    using kind, selected_id;
end $$;

create function public.editable_content(actor uuid, kind public.content_kind, selected_id integer default null)
returns setof jsonb language plpgsql set search_path = '' as $$
begin
  perform public.require_admin(actor, 'content');
  return query execute format('select public.content_data($1,id) || jsonb_build_object(''state'', state,
      ''liveRevisionId'', (select p.id from public.%I p where p.parent_id = revisions.parent_id and p.state = ''published''),
      ''liveEditNumber'', (select p.edit_number from public.%I p where p.parent_id = revisions.parent_id and p.state = ''published''))
    from (select distinct on (parent_id) id,state,parent_id from public.%I
     where ($2 is null or parent_id = $2)
     order by parent_id, state, version desc) revisions order by parent_id', kind || '_revisions', kind || '_revisions', kind || '_revisions') using kind, selected_id;
end $$;

create function public.write_content(actor uuid, kind public.content_kind, selected_id integer,
  expected_revision bigint, expected_edit integer, operation text, input jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare
  parent_table text := kind || 's';
  revision_table text := kind || '_revisions';
  parent integer := selected_id;
  revision bigint;
  version_number integer;
  edit integer;
  state public.revision_state;
  cohort_id bigint;
  thumbnail uuid;
  pdf uuid;
  image jsonb;
  asset uuid;
  public_asset uuid;
begin
  perform public.require_admin(actor, 'content');
  if parent is null then
    if operation <> 'save' then raise invalid_parameter_value; end if;
    execute format('insert into public.%I default values returning id', parent_table) into parent;
  end if;
  execute format('select id from public.%I where id = $1 for update', parent_table) into strict parent using parent;

  execute format('select id, edit_number, state from public.%I where parent_id = $1 order by state,version desc limit 1',
    revision_table) into revision, edit, state using parent;
  if operation = 'unpublish' then
    execute format('select id, edit_number from public.%I where parent_id=$1 and state=''published''',
      revision_table) into revision, edit using parent;
  end if;
  if expected_revision is distinct from revision or expected_edit is distinct from edit then
    raise exception using errcode = '40001', message = 'Content was edited';
  end if;

  if operation = 'save' then
    thumbnail := (input->>'thumbnailId')::uuid;
    pdf := (input->>'pdfId')::uuid;
    if input->>'cohort' is not null then
      select c.id into strict cohort_id from public.cohorts c where c.ordinal = (input->>'cohort')::integer;
    end if;
    if state is distinct from 'draft' then
      execute format('select coalesce(max(version),0)+1 from public.%I where parent_id=$1', revision_table)
        into version_number using parent;
      edit := 1;
    else
      -- A replacement draft has a fresh revision ID and retains its version number.
      execute format('delete from public.%I where id=$1 returning version, edit_number+1', revision_table)
        into version_number, edit using revision;
    end if;

    case kind
      when 'project' then
        insert into public.project_revisions (parent_id,version,edit_number,editor,state,name,title,description,cohort_id,
          thumbnail_id,pdf_id,legacy_thumbnail,legacy_pdf)
        values (parent,version_number,edit,actor,'draft',input->>'name',input->>'title',input->>'description',cohort_id,
          thumbnail,pdf,input->>'legacyThumbnail',input->>'legacyPdf') returning id into revision;
        insert into public.project_revision_images
          select revision, ordinal-1, (value->>'mediaId')::uuid, value->>'legacyUrl'
          from jsonb_array_elements(input->'images') with ordinality as items(value,ordinal);
      when 'organizer' then
        insert into public.organizer_revisions (parent_id,version,edit_number,editor,state,name,author,position,introduction,
          mbti,emoji,is_archived,thumbnail_id,legacy_thumbnail)
        values (parent,version_number,edit,actor,'draft',input->>'name',input->>'author',input->>'position',input->>'description',
          input->>'mbti',input->>'emoji',(input->>'isArchived')::boolean,thumbnail,input->>'legacyThumbnail') returning id into revision;
        insert into public.organizer_revision_details
          select revision,value->>'kind',ordinal-1,value->>'body'
          from jsonb_array_elements(input->'details') with ordinality as items(value,ordinal);
      when 'review' then
        insert into public.review_revisions (parent_id,version,edit_number,editor,state,name,position,body,cohort_id,project_id,original_project_name)
        values (parent,version_number,edit,actor,'draft',input->>'name',input->>'position',input->>'description',cohort_id,
          (input->>'projectId')::integer,coalesce(input->>'originalProjectName','')) returning id into revision;
    end case;

    execute format('insert into public.%I select $1,ordinal-1,value->>''kind'',value->>''url''
      from jsonb_array_elements($2) with ordinality as items(value,ordinal)', kind || '_revision_links') using revision,input->'links';
    if kind <> 'review' then
      insert into public.skills(label) select distinct value from jsonb_array_elements_text(input->'skills') as items(value)
        order by value on conflict (label) do nothing;
      execute format('insert into public.%I
        select $1,s.id,min(ordinal)-1 from jsonb_array_elements_text($2) with ordinality as items(value,ordinal)
        join public.skills s on s.label=value group by s.id', kind || '_revision_skills') using revision,input->'skills';
    end if;

  elsif operation = 'publish' and state = 'draft' then
    -- Every replacement must be a verified byte-for-byte public copy of the draft object.
    for asset in
      select thumbnail_id from public.project_revisions where kind='project' and id=revision
      union select pdf_id from public.project_revisions where kind='project' and id=revision
      union select media_id from public.project_revision_images where kind='project' and revision_id=revision
      union select thumbnail_id from public.organizer_revisions where kind='organizer' and id=revision
    loop
      continue when asset is null;
      select p.id into strict public_asset from public.media_assets d join public.media_assets p
      on p.sha256=d.sha256 and p.mime=d.mime and p.bytes=d.bytes
      where d.id=asset and d.ready and p.ready and p.bucket='cms-public'
        and p.id=coalesce((input->>asset::text)::uuid,asset);
      if kind = 'project' then
        update public.project_revisions set
          thumbnail_id=case when thumbnail_id=asset then public_asset else thumbnail_id end,
          pdf_id=case when pdf_id=asset then public_asset else pdf_id end where id=revision;
        update public.project_revision_images set media_id=public_asset where revision_id=revision and media_id=asset;
      else
        update public.organizer_revisions set thumbnail_id=public_asset where id=revision and thumbnail_id=asset;
      end if;
    end loop;
    execute format('update public.%I set state=''archived'' where parent_id=$1 and state=''published''', revision_table) using parent;
    execute format('update public.%I set state=''published'' where id=$1', revision_table) using revision;
  elsif operation = 'unpublish' and revision is not null then
    execute format('update public.%I set state=''archived'' where id=$1', revision_table) using revision;
  else
    raise invalid_parameter_value;
  end if;
  insert into public.admin_audit (actor,operation,target) values (actor,operation,kind || '/' || parent);
  return jsonb_build_object('id',parent,'revisionId',revision,'editNumber',edit);
end $$;

do $$
declare item regclass;
begin
  foreach item in array array['public.projects','public.organizers','public.reviews','public.skills','public.media_assets',
    'public.cms_uploads','public.project_revisions','public.organizer_revisions','public.review_revisions',
    'public.project_revision_images','public.organizer_revision_details','public.project_revision_links',
    'public.organizer_revision_links','public.review_revision_links','public.project_revision_skills',
    'public.organizer_revision_skills']::regclass[]
  loop
    execute format('alter table %s enable row level security', item);
    execute format('revoke all on %s from anon, authenticated', item);
    execute format('grant select, insert, update, delete on %s to service_role', item);
  end loop;
end $$;

