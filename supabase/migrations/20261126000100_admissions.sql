create table public.cohorts (
  id bigint generated by default as identity primary key,
  ordinal integer not null unique check (ordinal > 0)
);

create type public.admin_permission as enum ('admissions', 'content');
create table public.admin_accounts (
  user_id uuid primary key references auth.users on delete cascade,
  active boolean not null default true
);
create table public.admin_permissions (
  user_id uuid references public.admin_accounts on delete cascade,
  permission public.admin_permission not null,
  primary key (user_id, permission)
);
create table public.admin_audit (
  id bigint generated always as identity primary key,
  actor uuid not null,
  occurred_at timestamptz not null default now(),
  operation text not null,
  target text not null
);

create type public.application_position as enum ('FRONTEND', 'BACKEND', 'ANDROID', 'IOS', 'DESIGNER');
create type public.application_status as enum ('NONE', 'PASSED', 'FAILED', 'WAITLISTED');
create table public.admission_events (
  id bigint generated by default as identity primary key check (id > 0),
  cohort_id bigint not null references public.cohorts,
  name text not null check (length(trim(name)) between 1 and 160),
  starts_at timestamptz not null,
  ends_at timestamptz check (ends_at > starts_at),
  ready boolean not null default false,
  is_current boolean not null default false,
  unique (cohort_id, id)
);
create unique index admission_current on public.admission_events (is_current) where is_current;

create table public.applications (
  id bigint generated always as identity primary key,
  cohort_id bigint not null references public.cohorts,
  position public.application_position not null,
  name_ciphertext text not null,
  email_ciphertext text not null,
  name_hmac text not null check (name_hmac ~ '^[a-f0-9]{64}$'),
  email_hmac text not null check (email_hmac ~ '^[a-f0-9]{64}$'),
  unique (cohort_id, id),
  unique (cohort_id, name_hmac, email_hmac)
);

create table public.application_results (
  event_id bigint not null,
  application_id bigint not null,
  cohort_id bigint not null,
  status public.application_status not null,
  primary key (event_id, application_id),
  foreign key (cohort_id, event_id) references public.admission_events (cohort_id, id),
  foreign key (cohort_id, application_id) references public.applications (cohort_id, id)
);

create table public.admission_rate_limits (
  bucket timestamptz not null,
  visitor text not null,
  hits integer not null default 1,
  primary key (bucket, visitor)
);

-- Only the server's service role calls these RPCs. The actor comes from verified Auth.
create function public.cms_permissions(actor uuid) returns setof public.admin_permission
language sql stable set search_path = '' as $$
  select p.permission from public.admin_accounts a
  join public.admin_permissions p using (user_id)
  where a.user_id = actor and a.active
$$;

create function public.require_admin(actor uuid, job public.admin_permission) returns void
language plpgsql set search_path = '' as $$
begin
  perform 1 from public.admin_accounts a join public.admin_permissions p using (user_id)
  where a.user_id = actor and a.active and p.permission = job
  for share of a, p;
  if not found then raise insufficient_privilege; end if;
end $$;

create function public.event_open(event public.admission_events, at_time timestamptz) returns boolean
language sql immutable set search_path = '' as $$
  select event.ready and at_time >= event.starts_at and (event.ends_at is null or at_time < event.ends_at)
$$;

create function public.current_admission() returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object('id', e.id, 'name', e.name,
    'resultAnnouncementDateTime', to_char(e.starts_at at time zone 'Asia/Seoul', 'YYYY-MM-DD"T"HH24:MI:SS') || '+09:00',
    'isResultAnnounced', public.event_open(e, statement_timestamp()))
  from public.admission_events e where e.is_current
$$;

create function public.check_admission(event_id bigint, name_hash text, email_hash text, visitor text) returns jsonb
language plpgsql set search_path = '' as $$
declare
  e public.admission_events;
  result record;
  attempts integer;
begin
  delete from public.admission_rate_limits where bucket < statement_timestamp() - interval '2 hours';
  insert into public.admission_rate_limits as rate (bucket, visitor)
  values (date_trunc('minute', statement_timestamp()), check_admission.visitor)
  on conflict on constraint admission_rate_limits_pkey do update set hits = least(rate.hits + 1, 21)
  returning hits into attempts;
  if attempts > 20 then return jsonb_build_object('code', 'RATE'); end if;

  select * into e from public.admission_events where id = check_admission.event_id for share;
  if not found or not public.event_open(e, statement_timestamp()) then
    return jsonb_build_object('code', 'AP002');
  end if;

  select a.name_ciphertext, r.status into result from public.applications a
  join public.application_results r on r.cohort_id = a.cohort_id and r.application_id = a.id
  where a.cohort_id = e.cohort_id and r.event_id = e.id and a.name_hmac = name_hash and a.email_hmac = email_hash;
  if not found then return jsonb_build_object('code', 'AP001'); end if;
  return jsonb_build_object('eventName', e.name, 'nameCiphertext', result.name_ciphertext, 'status', result.status);
end $$;

create function public.admissions_write(actor uuid, operation text, input jsonb) returns jsonb
language plpgsql set search_path = '' as $$
declare
  target_id bigint;
  cohort public.cohorts;
  event public.admission_events;
  existing_position public.application_position;
  position public.application_position;
  starts timestamptz;
  item jsonb;
  inserted_count integer := 0;
  target text;
begin
  perform public.require_admin(actor, 'admissions');
  case operation
    when 'cohort' then
      insert into public.cohorts (ordinal) values ((input->>'ordinal')::integer)
      on conflict (ordinal) do nothing returning id into target_id;
      if target_id is null then return jsonb_build_object('outcome', 'duplicate'); end if;
      target := target_id::text;
    when 'applicant' then
      select * into strict cohort from public.cohorts where id = (input->>'cohortId')::bigint for update;
      position := (input->>'position')::public.application_position;
      insert into public.applications (cohort_id, position, name_ciphertext, email_ciphertext, name_hmac, email_hmac)
      values (cohort.id, position, input->>'nameCiphertext', input->>'emailCiphertext', input->>'nameHash', input->>'emailHash')
      on conflict (cohort_id, name_hmac, email_hmac) do nothing returning id into target_id;
      if target_id is null then
        select a.position into existing_position from public.applications a
        where a.cohort_id = cohort.id and a.name_hmac = input->>'nameHash' and a.email_hmac = input->>'emailHash';
        return jsonb_build_object('outcome', case when existing_position = position then 'duplicate' else 'conflict' end);
      end if;
      target := target_id::text;
    when 'event' then
      perform pg_advisory_xact_lock(160026);
      select * into strict cohort from public.cohorts where id = (input->>'cohortId')::bigint;
      target_id := (input->>'id')::bigint;
      select * into event from public.admission_events where id = target_id for update;
      if found and event.cohort_id <> cohort.id then raise check_violation; end if;
      starts := (input->>'startsAt')::timestamptz;
      if cohort.ordinal = 16 and starts <> timestamptz '2026-12-19 00:00:00+09' then raise check_violation; end if;
      if (input->>'current')::boolean then
        update public.admission_events set is_current = false where is_current and id <> target_id;
      end if;
      insert into public.admission_events (id, cohort_id, name, starts_at, ends_at, ready, is_current)
      values (target_id, cohort.id, input->>'name', starts, (input->>'endsAt')::timestamptz, false, (input->>'current')::boolean)
      on conflict (id) do update set name = excluded.name, starts_at = excluded.starts_at,
        ends_at = excluded.ends_at, ready = false, is_current = excluded.is_current;
      target := target_id::text;
    when 'ready', 'close' then
      update public.admission_events set ready = operation = 'ready' where id = (input->>'eventId')::bigint
      returning id into strict target_id;
      target := target_id::text;
    when 'results' then
      select * into strict event from public.admission_events where id = (input->>'eventId')::bigint for update;
      for item in select value from jsonb_array_elements(input->'rows') loop
        select id into strict target_id from public.applications
        where cohort_id = event.cohort_id and name_hmac = item->>'nameHash' and email_hmac = item->>'emailHash';
        insert into public.application_results as r (event_id, application_id, cohort_id, status)
        values (event.id, target_id, event.cohort_id, (item->>'status')::public.application_status)
        on conflict (event_id, application_id) do update set status = excluded.status
        where r.status is distinct from excluded.status;
        if found then
          insert into public.admin_audit (actor, operation, target) values (actor, 'result', event.id || '/' || target_id);
          inserted_count := inserted_count + 1;
        end if;
      end loop;
      return jsonb_build_object('outcome', 'saved', 'changed', inserted_count);
    else raise invalid_parameter_value;
  end case;
  insert into public.admin_audit (actor, operation, target) values (actor, operation, target);
  return jsonb_build_object('outcome', 'saved', 'id', target_id);
end $$;

create function public.admissions_read(actor uuid, selected_event bigint, name_hash text, email_hash text) returns jsonb
language plpgsql set search_path = '' as $$
begin
  perform public.require_admin(actor, 'admissions');
  return jsonb_build_object(
    'cohorts', coalesce((select jsonb_agg(c order by ordinal desc) from public.cohorts c), '[]'),
    'events', coalesce((select jsonb_agg(e order by id desc) from public.admission_events e), '[]'),
    'match', (select jsonb_build_object('id', a.id, 'position', a.position, 'status', r.status)
      from public.admission_events e join public.applications a on a.cohort_id = e.cohort_id
      left join public.application_results r on r.event_id = e.id and r.application_id = a.id
      where e.id = selected_event and a.name_hmac = name_hash and a.email_hmac = email_hash)
  );
end $$;

